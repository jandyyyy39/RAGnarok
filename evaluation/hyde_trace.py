"""
HyDE RAG Qualitative Trace Viewer
=====================================
Shows every step of the HyDE (Hypothetical Document Embeddings) retrieval:
  - Each of the 3 hypothetical SRD paragraphs generated by the LLM
  - Which chunks each hypothesis retrieved (k=8 each)
  - The direct query search results (k=5 fallback)
  - The overlap re-ranking scores before final slice
  - The final 5 chunks passed to the LLM
  - The final ruling output

Usage:
    python evaluation/hyde_trace.py -p local
    python evaluation/hyde_trace.py -p groq
    python evaluation/hyde_trace.py -p groq -q "I try to grapple the guard"
    python evaluation/hyde_trace.py -p groq -i 2    # test case #2 from test_cases.json
"""

import re
import sys
import os
import argparse
import time
import torch

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))

from config import Config
from langchain_huggingface import HuggingFaceEmbeddings
from langchain_chroma import Chroma
from openai import OpenAI
from groq import Groq

DB_PATH = "data/chroma_db"
WORLD_CTX = "Location: The Black Boar Tavern. Active NPCs: Thrain Blackbeard."


def _strip_think_tags(text: str) -> str:
    return re.sub(r"<think>.*?</think>", "", text, flags=re.DOTALL).strip()


def divider(char="═", width=70):
    print(char * width)


class HyDETracer:
    def __init__(self, client, model: str):
        self.client = client
        self.model = model

        device = 'cuda' if torch.cuda.is_available() else 'cpu'
        print(f"[Tracer] Loading embeddings on {device.upper()}...")
        self.embeddings = HuggingFaceEmbeddings(
            model_name=Config.EMBEDDING_MODEL,
            model_kwargs={'device': device})
        self.vectorstore = Chroma(
            persist_directory=DB_PATH,
            embedding_function=self.embeddings)
        print("[Tracer] Ready.\n")

    _STOP_WORDS = {
        "i", "me", "my", "we", "you", "he", "she", "it", "they", "them",
        "a", "an", "the", "to", "of", "in", "on", "at", "by", "for",
        "and", "or", "but", "if", "so", "as", "is", "am", "are", "was",
        "be", "been", "being", "do", "does", "did", "can", "will", "would",
        "could", "should", "may", "might", "shall", "have", "has", "had",
        "not", "no", "up", "out", "off", "with", "from", "into", "than",
        "that", "this", "these", "those", "what", "which", "who", "how",
        "want", "try", "get", "go", "let", "make", "take", "use", "see",
        "know", "think", "some", "more", "about", "there", "their", "then",
    }

    _HYPOTHESIS_FOCUS = [
        "Focus on the PRIMARY ability check or attack roll and how it is resolved.",
        "Focus on the CONDITIONS, REQUIREMENTS, or LIMITATIONS that apply to this action.",
        "Focus on the CONSEQUENCES, EFFECTS, or what happens after the roll succeeds or fails.",
    ]

    @staticmethod
    def _normalize_key(text: str) -> str:
        stripped = re.sub(r'\[([^\]]+)\]\([^)]+\)', r'\1', text)
        return stripped[:150].lower().strip()

    def _generate_hypothesis(self, player_action, world_context, focus: str = "", temperature: float = 0.1):
        focus_line = f"\nFOCUS: {focus}" if focus else ""
        prompt = f"""You are a D&D 5e rules encyclopedia.
Write a single paragraph (3-5 sentences) from the official D&D 5e SRD
that contains the EXACT rules mechanic for this player action.

Use precise SRD language: skill names (Athletics, Acrobatics, Stealth,
Deception, Persuasion, Perception, Animal Handling, Medicine, etc.),
action types (action, bonus action, reaction), and mechanical terms
(DC, contested check, saving throw, ability check).{focus_line}

Player action: "{player_action}"
Game context: {world_context}

Begin directly with the mechanic name or rule heading. Write ONLY the
rules text as it would appear in the SRD. No commentary.
If no ability check or roll is needed, write:
'This action does not require an ability check or saving throw. It succeeds automatically.'"""

        resp = self.client.chat.completions.create(
            messages=[{"role": "user", "content": prompt}],
            model=self.model,
            temperature=temperature,
            max_tokens=600)
        return _strip_think_tags(resp.choices[0].message.content)

    def _get_ruling(self, chunks, player_action, world_context):
        context_text = "\n\n---\n\n".join(chunks)
        prompt = f"""SYSTEM: You are the Rules Arbiter for a D&D 5e game.
Your job is to interpret the player's intent based on the official rules.

WORLD CONTEXT: {world_context}
PLAYER ACTION: "{player_action}"

RELEVANT RULES FROM SRD:
{context_text}

INSTRUCTIONS:
1. If the action is trivial, state 'No check required' and explain briefly why.
2. If a check IS required, identify EXACTLY ONE primary Ability Check, Saving Throw, or Attack Roll.
3. For the resolution, use EXACTLY what the SRD rules above specify:
   - If the rules say it is a CONTESTED CHECK (one roll vs another), state both rolls (e.g. "Dexterity (Stealth) contested by Wisdom (Perception)"). Do NOT invent a DC.
   - If the rules specify a fixed DC or saving throw, state that DC (Easy=10, Medium=15, Hard=20, Very Hard=25).
4. Output strict, concise mechanics only. No conversational text."""

        resp = self.client.chat.completions.create(
            messages=[
                {"role": "system", "content": "You are a precise D&D 5e rules engine."},
                {"role": "user", "content": prompt}
            ],
            model=self.model,
            temperature=0.1,
            max_tokens=150)
        return resp.choices[0].message.content

    def trace(self, player_action, world_context=WORLD_CTX):
        start_total = time.time()

        print()
        divider("═")
        print(f"  HyDE TRACE — QUERY: \"{player_action}\"")
        divider("═")
        print(f"  Model   : {self.model}")
        print(f"  Context : {world_context}")
        print(f"  Strategy: Generate 3 hypothetical SRD paragraphs → search with each (k=8)")
        print(f"            + direct query search (k=5) → overlap re-rank → top 5")
        divider("─")

        seen = set()
        merged = []

        def _add(doc):
            key = self._normalize_key(doc.page_content)
            if key not in seen:
                seen.add(key)
                merged.append(doc)
                return True
            return False

        # ── HYPOTHESIS GENERATION + SEARCH ───────────────────────────────────
        hyp_docs_text = []
        for hyp_num in range(1, 4):
            focus = self._HYPOTHESIS_FOCUS[hyp_num - 1]
            temp = 0.1 + (hyp_num - 1) * 0.2  # 0.1, 0.3, 0.5
            print(f"\n{'─'*70}")
            print(f"  HYPOTHESIS {hyp_num}/3  |  temp={temp:.1f}  |  {focus}")
            print(f"{'─'*70}\n")

            hyp = self._generate_hypothesis(player_action, world_context, focus=focus, temperature=temp)
            hyp_docs_text.append(hyp)

            print(f"  Generated paragraph:")
            print(f"  \"{hyp[:400].strip()}{'...' if len(hyp) > 400 else ''}\"")
            print()

            print(f"  → Searching vector store with this hypothesis (k=8)...")
            results = self.vectorstore.similarity_search(hyp, k=8)
            new_count = sum(1 for doc in results if _add(doc))
            print(f"     {new_count} new unique chunks added  |  Pool size: {len(merged)}")

        # ── DIRECT QUERY FALLBACK ─────────────────────────────────────────────
        print(f"\n{'─'*70}")
        print(f"  DIRECT QUERY FALLBACK  |  Search with original player query (k=5)")
        print(f"  (Catches obvious SRD terms that hypothetical docs might miss)")
        print(f"{'─'*70}\n")
        print(f"  Query: \"{player_action}\"")

        fallback_results = self.vectorstore.similarity_search(player_action, k=5)
        fallback_new = sum(1 for doc in fallback_results if _add(doc))
        print(f"  {fallback_new} new unique chunks added  |  Total pool: {len(merged)}")

        # ── OVERLAP RE-RANKING ────────────────────────────────────────────────
        print(f"\n{'─'*70}")
        print(f"  OVERLAP RE-RANKING  |  Score each chunk by query word overlap (stop words excluded)")
        print(f"  (Common words like 'i', 'want', 'this' filtered — only meaningful terms scored)")
        print(f"{'─'*70}\n")

        query_words = {w for w in player_action.lower().split() if w not in self._STOP_WORDS}
        print(f"  Signal words (after stop-word filter): {sorted(query_words)}\n")

        scored = []
        for doc in merged:
            score = sum(1 for w in query_words if w in doc.page_content.lower())
            scored.append((score, doc))
        scored.sort(key=lambda x: x[0], reverse=True)

        for i, (score, doc) in enumerate(scored[:10], 1):
            marker = "← TOP 5" if i <= 5 else ""
            print(f"  Rank {i:2d}  overlap={score}  {marker}")
            print(f"         \"{doc.page_content[:120].strip()}...\"")
            print()

        # ── FINAL CHUNKS ─────────────────────────────────────────────────────
        final = [doc for _, doc in scored[:5]]
        print(f"{'─'*70}")
        print(f"  FINAL CONTEXT  |  Top 5 chunks after overlap re-ranking")
        print(f"{'─'*70}\n")
        for i, doc in enumerate(final, 1):
            print(f"  ── Chunk {i} ──────────────────────────────")
            print(f"  {doc.page_content.strip()}")
            print()

        # ── FINAL RULING ─────────────────────────────────────────────────────
        print(f"{'─'*70}")
        print(f"  FINAL RULING")
        print(f"{'─'*70}\n")
        ruling = self._get_ruling([doc.page_content for doc in final], player_action, world_context)
        print(f"  {ruling.strip()}")

        elapsed = time.time() - start_total
        print(f"\n{'─'*70}")
        print(f"  Total time: {elapsed:.1f}s  |  LLM calls: 4 (3 hypotheses + 1 ruling)")
        divider("═")
        print()

        return {
            "query": player_action,
            "hypotheses": hyp_docs_text,
            "chunks_final": [doc.page_content for doc in final],
            "ruling": ruling,
            "latency": elapsed,
        }


def main():
    parser = argparse.ArgumentParser(description="HyDE RAG qualitative trace viewer")
    parser.add_argument("-p", "--profile", choices=["local", "fast", "groq"], default="groq")
    parser.add_argument("-q", "--query", type=str, default=None)
    parser.add_argument("-i", "--id", type=int, default=None)
    args = parser.parse_args()

    if args.query:
        query = args.query
    elif args.id is not None:
        import json
        with open("evaluation/test_cases.json") as f:
            cases = json.load(f)
        match = next((c for c in cases if c["id"] == args.id), None)
        if not match:
            print(f"No test case with id={args.id}")
            sys.exit(1)
        query = match["query"]
        print(f"[Test case #{args.id}] category={match['category']}  type={match['query_type']}")
        print(f"[Expected mechanic] {match['description']}")
        print(f"[Primary keywords]  {match['primary_keywords']}")
    else:
        query = "I want to sneak past the sleeping guards"

    if args.profile == "local":
        print(f"Using LOCAL model: {Config.LLM_MODEL['LOCAL']}")
        client = OpenAI(base_url=Config.OLLAMA_BASE_URL, api_key="ollama")
        model = Config.LLM_MODEL['LOCAL']
    elif args.profile == "fast":
        print(f"Using GROQ FAST model: {Config.LLM_MODEL['GROQ_FAST']}")
        client = Groq(api_key=Config.GROQ_API_KEY)
        model = Config.LLM_MODEL['GROQ_FAST']
    else:
        print(f"Using GROQ model: {Config.LLM_MODEL['GROQ']}")
        client = Groq(api_key=Config.GROQ_API_KEY)
        model = Config.LLM_MODEL['GROQ']

    tracer = HyDETracer(client, model)
    tracer.trace(query)


if __name__ == "__main__":
    main()
